def _wizard_services(non_interactive: bool) -> None:
    _step("Step C  ·  Background services (optional)")
    venv = ROOT / ".venv"
    if not venv.exists():
        _warn("No .venv — skipping service installation")
        return

    if non_interactive:
        _info("Skipping service install (non-interactive)")
        return
    if not _yes("  Install always-on background services (daily refresh + intraday capture)?", default=False):
        _info("Skipped — you can install later with: make -C installer services")
        return

    sysname = platform.system()
    PLIST_TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    SYSTEMD_TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)

    if sysname == "Darwin":
        units = {
            "com.agentadda.daily_refresh.plist":    LAUNCHD_DAILY_REFRESH,
            "com.agentadda.intraday_capture.plist": LAUNCHD_INTRADAY_CAPTURE,
        }
        target_dir = Path.home() / "Library" / "LaunchAgents"
        target_dir.mkdir(parents=True, exist_ok=True)
        for name, body in units.items():
            rendered = body.replace("__VENV__", str(venv)).replace("__ROOT__", str(ROOT))
            staged = PLIST_TEMPLATE_DIR / name
            staged.write_text(rendered)
            target = target_dir / name
            shutil.copy(staged, target)
            subprocess.run(["launchctl", "unload", str(target)], capture_output=True)
            r = subprocess.run(["launchctl", "load", str(target)], capture_output=True, text=True)
            if r.returncode == 0:
                _ok(f"Loaded {name}")
            else:
                _warn(f"launchctl load {name}: {r.stderr.strip()}")
    elif sysname == "Linux":
        units = {
            "agentadda-daily-refresh.service":    SYSTEMD_DAILY_REFRESH,
            "agentadda-intraday-capture.service": SYSTEMD_INTRADAY_CAPTURE,
        }
        for name, body in units.items():
            rendered = body.replace("__VENV__", str(venv)).replace("__ROOT__", str(ROOT))
            staged = SYSTEMD_TEMPLATE_DIR / name
            staged.write_text(rendered)
            _info(f"Wrote {staged.relative_to(ROOT)}")
        print(f"\n    {DIM('To enable, copy to /etc/systemd/system and run:')}")
        print(f"    {CYN(f'sudo cp {SYSTEMD_TEMPLATE_DIR}/*.service /etc/systemd/system/')}")
        print(f"    {CYN('sudo systemctl daemon-reload && sudo systemctl enable --now agentadda-intraday-capture.service')}")
    else:
        _warn(f"No service manager available for {sysname}")


# ─────────────────────────────────────────────────────────────────────────────
# 4.  Smoke test (delegate to doctor.py)
# ─────────────────────────────────────────────────────────────────────────────
def _wizard_doctor() -> int:
    _step("Step D  ·  Health check")
    doctor = ROOT / "installer" / "doctor.py"
    if not doctor.exists():
        _warn("doctor.py not found — skipping")
        return 0
    return subprocess.run([sys.executable, str(doctor)]).returncode


# ─────────────────────────────────────────────────────────────────────────────
# helpers
# ─────────────────────────────────────────────────────────────────────────────
def _yes(prompt: str, *, default: bool = True) -> bool:
    suffix = " [Y/n]" if default else " [y/N]"
    try:
        ans = input(prompt + suffix + " ").strip().lower()
    except EOFError:
        return default
    if not ans:
        return default
    return ans in ("y", "yes")


# ─────────────────────────────────────────────────────────────────────────────
# main
# ─────────────────────────────────────────────────────────────────────────────
def main() -> int:
    p = argparse.ArgumentParser(description="Agent Adda interactive setup wizard.")
    p.add_argument("--non-interactive", action="store_true", help="Use existing .env / defaults; no prompts.")
    p.add_argument("--check-only",      action="store_true", help="Run health checks only.")
    p.add_argument("--skip-system", action="store_true", help=argparse.SUPPRESS)
    p.add_argument("--skip-wizard", action="store_true", help=argparse.SUPPRESS)
    p.add_argument("--check",       action="store_true", help=argparse.SUPPRESS)
    args = p.parse_args()

    if args.check_only or args.check:
        return _wizard_doctor()

    values = _wizard_env(non_interactive=args.non_interactive)
    _wizard_postgres(values, non_interactive=args.non_interactive)
    _wizard_services(non_interactive=args.non_interactive)
    rc = _wizard_doctor()

    print(f"\n{BOLD(GRN('Wizard complete.'))}\n")
    print(f"  Run the agent:    {CYN('.venv/bin/python nse_agent.py')}")
    print(f"  Re-run wizard:    {CYN('.venv/bin/python installer/setup_wizard.py')}")
    print(f"  Health check:     {CYN('.venv/bin/python installer/doctor.py')}\n")
    return rc


if __name__ == "__main__":
    sys.exit(main())
