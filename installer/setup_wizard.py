ROOT = Path(__file__).resolve().parent.parent
ENV_PATH = ROOT / ".env"
ENV_TEMPLATE_PATH = ROOT / "installer" / ".env.template"
PLIST_TEMPLATE_DIR = ROOT / "installer" / "launchd"
SYSTEMD_TEMPLATE_DIR = ROOT / "installer" / "systemd"

# ─────────────────────────────────────────────────────────────────────────────
# tiny ANSI helpers (no external dep)
# ─────────────────────────────────────────────────────────────────────────────
_TTY = sys.stdout.isatty()
def _c(code: str, s: str) -> str:
    return f"\033[{code}m{s}\033[0m" if _TTY else s
BOLD = lambda s: _c("1", s)
DIM  = lambda s: _c("2", s)
RED  = lambda s: _c("31", s)
GRN  = lambda s: _c("32", s)
YEL  = lambda s: _c("33", s)
CYN  = lambda s: _c("36", s)

def _step(title: str) -> None:
    print(f"\n{BOLD('── ' + title + ' ──')}")
def _ok(msg: str) -> None:    print(f"  {GRN('✓')} {msg}")
def _info(msg: str) -> None:  print(f"  {CYN('•')} {msg}")
def _warn(msg: str) -> None:  print(f"  {YEL('⚠')} {msg}")
def _err(msg: str) -> None:   print(f"  {RED('✗')} {msg}")


# ─────────────────────────────────────────────────────────────────────────────
# .env handling
# ─────────────────────────────────────────────────────────────────────────────
