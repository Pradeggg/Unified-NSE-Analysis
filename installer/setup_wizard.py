#!/usr/bin/env python3
"""Agent Adda — Interactive Setup Wizard.

Runs after install.sh and:
  1. Generates / updates .env from .env.template by prompting for each value
     (existing values preserved; user can press Enter to keep them).
  2. Verifies PostgreSQL connectivity (creates DB + role if asked).
  3. Applies idempotent SQL migrations under postgres/.
  4. Asks whether to install background services (launchd on macOS,
     systemd on Linux) and writes the unit files in place.
  5. Runs a smoke test (doctor.py) and prints next-steps.

All steps are skippable / re-runnable. Safe to call any number of times.

Usage:
    python installer/setup_wizard.py                # full interactive wizard
    python installer/setup_wizard.py --non-interactive  # use defaults / .env values, no prompts
    python installer/setup_wizard.py --check-only       # only run health checks

Env-vars handled (categorised; all optional unless marked REQUIRED):

  POSTGRES               REQUIRED   PG_DSN  (format: dbname=… user=… host=…)
  LLM PROVIDER           OPTIONAL   OPENAI_API_KEY, OPENAI_MODEL,
                                    OLLAMA_HOST,  OLLAMA_MODEL
  WEB SEARCH             OPTIONAL   SERPAPI_API_KEY, BING_SEARCH_KEY
  ANTHROPIC NARRATIVES   OPTIONAL   ANTHROPIC_API_KEY
  EMAIL REPORTS          OPTIONAL   SMTP_HOST, SMTP_PORT, SMTP_USER,
                                    SMTP_PASSWORD, EMAIL_FROM
  CAPTURE DAEMON KNOBS   OPTIONAL   AGENT_ADDA_CAPTURE_INTERVAL_SEC (=60)
                                    AGENT_ADDA_CAPTURE_RETENTION_MIN (=120)
                                    AGENT_ADDA_CAPTURE_PRUNE_SEC     (=1800)
"""
