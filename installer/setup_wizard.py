def _ensure_template() -> None:
    """Write installer/.env.template if it doesn't exist."""
    if not ENV_TEMPLATE_PATH.exists():
        ENV_TEMPLATE_PATH.parent.mkdir(parents=True, exist_ok=True)
        ENV_TEMPLATE_PATH.write_text(ENV_TEMPLATE_CONTENT)
        _ok(f"Wrote default template: {ENV_TEMPLATE_PATH.relative_to(ROOT)}")

def _load_env_file(path: Path) -> dict[str, str]:
    """Parse KEY=VALUE pairs from a .env file (no shell expansion)."""
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        k, _, v = s.partition("=")
        out[k.strip()] = v.strip().strip('"').strip("'")
    return out

def _save_env(path: Path, values: dict[str, str], template_text: str) -> None:
    """Re-emit the template, replacing each KEY= with the value from `values`.
    Comments and ordering are preserved."""
    out_lines: list[str] = []
    for line in template_text.splitlines():
        m = re.match(r"^([A-Z][A-Z0-9_]*)\s*=", line)
        if m and m.group(1) in values:
            out_lines.append(f"{m.group(1)}={values[m.group(1)]}")
        else:
            out_lines.append(line)
    path.write_text("\n".join(out_lines) + "\n")
    try:
        path.chmod(0o600)
    except OSError:
        pass


# ─────────────────────────────────────────────────────────────────────────────
# 1.  prompt-driven .env wizard
# ─────────────────────────────────────────────────────────────────────────────
def _prompt(label: str, current: str = "", *, secret: bool = False, default: str = "") -> str:
    """Prompt for a value. Empty input keeps `current` (or `default`)."""
    show = current or default
    suffix = f" [{DIM(show if not secret else '••••')}]" if show else ""
    raw = input(f"    {label}{suffix}: ").strip()
    return raw or current or default

def _wizard_env(non_interactive: bool) -> dict[str, str]:
    _step("Step A  ·  Configure .env")
    _ensure_template()
    template_text = ENV_TEMPLATE_PATH.read_text()
    existing = _load_env_file(ENV_PATH)

    if non_interactive:
        _info(".env left as-is (non-interactive mode)")
        return existing

    print(f"  {DIM('Press Enter to keep the existing value shown in brackets.')}")
    print(f"  {DIM('Leave blank to disable that integration.')}\n")

    values = dict(existing)

    # Required
    print(f"  {BOLD('PostgreSQL')}")
    values["PG_DSN"] = _prompt(
        "PG_DSN",
        existing.get("PG_DSN", "dbname=nse_market user=nse_admin host=/tmp"),
    )

    # LLM
    print(f"\n  {BOLD('LLM backend')}  {DIM('(at least one — both optional but agent has reduced features without)')}")
    values["OPENAI_API_KEY"] = _prompt("OPENAI_API_KEY", existing.get("OPENAI_API_KEY", ""), secret=True)
    values["OPENAI_MODEL"]   = _prompt("OPENAI_MODEL",   existing.get("OPENAI_MODEL", "gpt-4o"))
    values["OLLAMA_HOST"]    = _prompt("OLLAMA_HOST",    existing.get("OLLAMA_HOST", "http://localhost:11434"))
    values["OLLAMA_MODEL"]   = _prompt("OLLAMA_MODEL",   existing.get("OLLAMA_MODEL", "granite4"))

    print(f"\n  {BOLD('Optional integrations')}  {DIM('(press Enter to skip)')}")
    values["SERPAPI_API_KEY"]   = _prompt("SERPAPI_API_KEY (web search)",       existing.get("SERPAPI_API_KEY", ""), secret=True)
    values["ANTHROPIC_API_KEY"] = _prompt("ANTHROPIC_API_KEY (Claude narratives)", existing.get("ANTHROPIC_API_KEY", ""), secret=True)

    if _yes(f"\n  Configure {BOLD('email reports')}? (SMTP)", default=False):
        values["SMTP_HOST"]     = _prompt("SMTP_HOST",     existing.get("SMTP_HOST", ""))
        values["SMTP_PORT"]     = _prompt("SMTP_PORT",     existing.get("SMTP_PORT", "587"))
        values["SMTP_USER"]     = _prompt("SMTP_USER",     existing.get("SMTP_USER", ""))
        values["SMTP_PASSWORD"] = _prompt("SMTP_PASSWORD", existing.get("SMTP_PASSWORD", ""), secret=True)
        values["EMAIL_FROM"]    = _prompt("EMAIL_FROM",    existing.get("EMAIL_FROM", ""))

    _save_env(ENV_PATH, values, template_text)
    _ok(f"Wrote {ENV_PATH.relative_to(ROOT)} (chmod 600)")
    return values


# ─────────────────────────────────────────────────────────────────────────────
# 2.  PostgreSQL provisioning
# ─────────────────────────────────────────────────────────────────────────────
def _parse_dsn(dsn: str) -> dict[str, str]:
    parts = {}
    for tok in dsn.split():
        if "=" in tok:
            k, _, v = tok.partition("=")
            parts[k.strip()] = v.strip()
    return parts

def _wizard_postgres(values: dict[str, str], non_interactive: bool) -> bool:
    _step("Step B  ·  PostgreSQL")
    dsn = values.get("PG_DSN", "").strip()
    if not dsn:
        _err("PG_DSN is empty — skipping PG step")
        return False
    try:
        import psycopg2  # type: ignore
    except ImportError:
        _err("psycopg2 not installed — did install.sh complete?")
        return False

    parts = _parse_dsn(dsn)
    db   = parts.get("dbname", "nse_market")
    user = parts.get("user",   "nse_admin")

    # Try connection
    try:
        conn = psycopg2.connect(dsn, connect_timeout=5)
        conn.close()
        _ok(f"Connected to PostgreSQL: dbname={db} user={user}")
    except Exception as e:
        _warn(f"Cannot connect: {e}")
        if non_interactive or not _yes(f"  Try to {BOLD('create')} db '{db}' and role '{user}' via psql?", default=True):
            _err("Cannot proceed without DB. Re-run after fixing connectivity.")
            return False
        if not _create_db_and_role(db, user):
            return False
        try:
            psycopg2.connect(dsn, connect_timeout=5).close()
            _ok("Connected after provisioning.")
        except Exception as e2:
            _err(f"Still cannot connect: {e2}")
            return False

    # Apply migrations
    pg_dir = ROOT / "postgres"
    if not pg_dir.is_dir():
        _info("No postgres/ directory — skipping schema migrations")
        return True
    sql_files = sorted(pg_dir.glob("*.sql"))
    if not sql_files:
        _info("No .sql files under postgres/ — skipping migrations")
        return True
    _info(f"Applying {len(sql_files)} migration(s) from postgres/")
    conn = psycopg2.connect(dsn)
    conn.autocommit = True
    for f in sql_files:
        try:
            with conn.cursor() as cur:
                cur.execute(f.read_text())
            _ok(f"  applied {f.name}")
        except Exception as e:
            _warn(f"  {f.name} skipped/failed: {str(e).splitlines()[0]}")
    conn.close()
    return True

def _create_db_and_role(db: str, user: str) -> bool:
    """Use locally-running psql as superuser to create db+role idempotently."""
    if not shutil.which("psql"):
        _err("psql not on PATH; cannot auto-create DB")
        return False
    sql = (
        f"DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname='{user}') "
        f"THEN CREATE ROLE {user} LOGIN; END IF; END $$;\n"
        f"SELECT 'CREATE DATABASE {db} OWNER {user}' WHERE NOT EXISTS "
        f"(SELECT FROM pg_database WHERE datname='{db}')\\gexec\n"
    )
    try:
        proc = subprocess.run(
            ["psql", "-d", "postgres", "-v", "ON_ERROR_STOP=1", "-X"],
            input=sql, text=True, capture_output=True, timeout=20,
        )
        if proc.returncode != 0:
            _err(f"psql failed: {proc.stderr.strip()}")
            return False
        _ok(f"Provisioned db '{db}' and role '{user}'")
        return True
    except Exception as e:
        _err(f"psql call errored: {e}")
        return False


