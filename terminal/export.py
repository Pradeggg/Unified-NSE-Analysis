"""Session export to HTML/PDF."""
from __future__ import annotations
import os, re, datetime, html as _html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXPORT_DIR = os.path.join(ROOT, "data", "exports")


def _strip_ansi(text: str) -> str:
    return re.sub(r'\x1b\[[0-9;]*[mK]', '', text)


def _rich_markup_to_html(text: str) -> str:
    """Convert Rich markup tags to basic HTML styling."""
    text = _html.escape(text)
    # Bold
    text = re.sub(r'\[bold(?:\s+\w+)?\](.*?)\[/(?:bold\s*\w*|)\]', r'<strong>\1</strong>', text, flags=re.DOTALL)
    text = re.sub(r'\[bold\](.*?)\[/bold\]', r'<strong>\1</strong>', text, flags=re.DOTALL)
    # Colors
    text = re.sub(r'\[green\](.*?)\[/(?:green|)\]', r'<span style="color:#4ade80">\1</span>', text, flags=re.DOTALL)
    text = re.sub(r'\[red\](.*?)\[/(?:red|)\]', r'<span style="color:#f87171">\1</span>', text, flags=re.DOTALL)
    text = re.sub(r'\[yellow\](.*?)\[/(?:yellow|)\]', r'<span style="color:#fbbf24">\1</span>', text, flags=re.DOTALL)
    text = re.sub(r'\[cyan\](.*?)\[/(?:cyan|)\]', r'<span style="color:#22d3ee">\1</span>', text, flags=re.DOTALL)
    text = re.sub(r'\[dim\](.*?)\[/(?:dim|)\]', r'<span style="opacity:0.6">\1</span>', text, flags=re.DOTALL)
    # Strip remaining Rich tags
    text = re.sub(r'\[/?[a-zA-Z0-9_ #;:.]+\]', '', text)
    # Newlines to <br>
    text = text.replace('\n', '<br>')
    return text


