def export_session_html(messages: list[dict], symbol: str = "", label: str = "") -> str:
    """Export session messages to a styled HTML file. Returns the file path."""
    os.makedirs(EXPORT_DIR, exist_ok=True)

    ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    fname = f"{symbol+'_' if symbol else ''}{ts}.html"
    fpath = os.path.join(EXPORT_DIR, fname)

    title = f"{symbol} Research" if symbol else "Market Research"
    subtitle = f"Session exported {datetime.datetime.now().strftime('%d %b %Y, %H:%M')} IST"
    if label:
        subtitle = f"{label} · {subtitle}"

    user_msgs = [m for m in messages if m.get("role") == "user"]

    msgs_html_parts = []
    for msg in messages:
        role = msg.get("role", "assistant")
        content = _strip_ansi(msg.get("content", ""))
        content_html = _rich_markup_to_html(content)
        role_label = {"user": "👤 You", "assistant": "🤖 Agent Adda", "system": "⚙️ System"}.get(role, role.title())
        msgs_html_parts.append(f'''<div class="message {role}">
  <div class="message-header">{role_label}</div>
  <div class="message-body">{content_html}</div>
</div>''')

    html = HTML_TEMPLATE.format(
        title=title,
        subtitle=subtitle,
        n_turns=len(messages),
        n_user=len(user_msgs),
        exported_at=datetime.datetime.now().strftime("%H:%M"),
        messages_html="\n".join(msgs_html_parts),
        date=datetime.datetime.now().strftime("%d %b %Y"),
    )

    with open(fpath, "w", encoding="utf-8") as f:
        f.write(html)

    return fpath


def export_session_pdf(messages: list[dict], symbol: str = "", label: str = "") -> str:
    """Convert session to PDF. Falls back to HTML if PDF libs unavailable."""
    html_path = export_session_html(messages, symbol, label)
    pdf_path = html_path.replace(".html", ".pdf")

    # Try weasyprint
    try:
        import weasyprint
        weasyprint.HTML(filename=html_path).write_pdf(pdf_path)
        return pdf_path
    except ImportError:
        pass

    # Try pdfkit (requires wkhtmltopdf system binary)
    try:
        import pdfkit
        pdfkit.from_file(html_path, pdf_path)
        return pdf_path
    except Exception:
        pass

    # Fallback: return HTML path
    return html_path
